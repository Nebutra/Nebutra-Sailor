#!/usr/bin/env node
/**
 * Generate apps/landing/src/lib/seo/route-lastmod.generated.ts — a committed,
 * git-derived <lastmod> table for every SEO route pattern.
 *
 *   node scripts/generate-route-lastmod.mjs
 *
 * Why generated and committed rather than computed during `next build`:
 * Vercel builds from a shallow clone where per-file `git log` is unreliable, so
 * the timestamps are resolved here (full history available) and checked in
 * exactly like packages/platform/i18n/src/product-locales.generated.ts.
 *
 * Resolution per registry pattern:
 *   1. every page file under apps/landing/src/app/[lang]/** whose route path
 *      matches the pattern (route groups stripped, [param] → *)
 *   2. plus the data module(s) that family renders from
 *   → newest `git log -1 --format=%cI` across all of them
 * Patterns with no resolvable timestamp are omitted, so the consumer can omit
 * <lastmod> instead of inventing a build-time date.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const LANDING = join(REPO, "apps/landing");
const APP_ROOT = join(LANDING, "src/app/[lang]");
const REGISTRY = join(LANDING, "src/lib/seo/route-registry.ts");
const OUTPUT = join(LANDING, "src/lib/seo/route-lastmod.generated.ts");

/** Extra modules whose content drives a route family's rendered output. */
const DATA_DEPENDENCIES = {
  "/features": ["src/components/landing/features/package-feature-data.ts"],
  "/features/*": [
    "src/components/landing/features/package-feature-data.ts",
    "src/lib/constants/landing-data.ts",
  ],
  "/solutions": ["src/lib/constants/solutions-data.ts"],
  "/solutions/*": ["src/lib/constants/solutions-data.ts"],
  "/blog": ["src/lib/blog.ts", "src/lib/blog-fallback.ts"],
  "/blog/*": ["src/lib/blog.ts", "src/lib/blog-fallback.ts"],
  "/open": ["src/lib/constants/open-platform.ts"],
};

function readRegistryPatterns() {
  const source = readFileSync(REGISTRY, "utf8");
  const patterns = [];
  for (const match of source.matchAll(/pattern:\s*"([^"]+)"/g)) {
    patterns.push(match[1]);
  }
  if (patterns.length === 0) {
    throw new Error(`No route patterns found in ${relative(REPO, REGISTRY)}`);
  }
  return patterns;
}

function walkPageFiles(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      walkPageFiles(full, out);
    } else if (entry.name === "page.tsx" || entry.name === "page.ts") {
      out.push(full);
    }
  }
  return out;
}

/** apps/landing/src/app/[lang]/(marketing)/blog/[slug]/page.tsx → "/blog/*" */
function routePathForPageFile(file) {
  const segments = relative(APP_ROOT, dirname(file))
    .split("/")
    .filter((segment) => segment && !segment.startsWith("("))
    .map((segment) => (segment.startsWith("[") ? "*" : segment));
  return segments.length === 0 ? "/" : `/${segments.join("/")}`;
}

function matchesPattern(routePath, pattern) {
  if (routePath === pattern) return true;
  if (!pattern.endsWith("/*")) return false;
  return routePath.startsWith(pattern.slice(0, -1));
}

function committedIso(absoluteFile) {
  try {
    const out = execFileSync(
      "git",
      ["log", "-1", "--format=%cI", "--", relative(REPO, absoluteFile)],
      { cwd: REPO, encoding: "utf8" },
    ).trim();
    return out || undefined;
  } catch {
    return undefined;
  }
}

function existsFile(absolutePath) {
  try {
    return statSync(absolutePath).isFile();
  } catch {
    return false;
  }
}

function buildTable() {
  const patterns = readRegistryPatterns();
  const pageFiles = walkPageFiles(APP_ROOT);
  const table = {};

  for (const pattern of patterns) {
    const contributors = pageFiles.filter((file) =>
      matchesPattern(routePathForPageFile(file), pattern),
    );
    for (const rel of DATA_DEPENDENCIES[pattern] ?? []) {
      const absolute = join(LANDING, rel);
      if (existsFile(absolute)) contributors.push(absolute);
    }

    const timestamps = contributors
      .map(committedIso)
      .filter((value) => typeof value === "string")
      .sort();
    const newest = timestamps.at(-1);
    if (newest) table[pattern] = newest;
  }

  const body = Object.keys(table)
    .sort()
    .map((pattern) => `  ${JSON.stringify(pattern)}: ${JSON.stringify(table[pattern])},`)
    .join("\n");

  const contents = `/**
 * AUTO-GENERATED by scripts/generate-route-lastmod.mjs — do not hand-edit.
 * Source of truth: git commit time of the page + data modules that render each
 * pattern in apps/landing/src/lib/seo/route-registry.ts.
 * Regenerate with: pnpm gen:route-lastmod
 */
export const ROUTE_LASTMOD: Record<string, string> = {
${body}
};
`;

  return { contents, table, patterns };
}

function main() {
  const { contents, table, patterns } = buildTable();
  writeFileSync(OUTPUT, contents, "utf8");
  process.stdout.write(
    `route-lastmod: ${Object.keys(table).length}/${patterns.length} patterns resolved → ${relative(REPO, OUTPUT)}\n`,
  );
}

/**
 * `--check` — is the committed snapshot byte-identical to what this script
 * would generate right now? Writes nothing; exits 1 with a per-pattern diff on
 * mismatch.
 *
 * Note this is NOT usable as a pull-request gate: the table is built from each
 * contributing file's `git log -1 --format=%cI`, so regenerating before
 * committing records the PREVIOUS commit's time and the gate would fail on the
 * new one — an unsatisfiable two-commit dance on every landing page edit. It is
 * a local diagnostic and the change detector for
 * .github/workflows/route-lastmod.yml, which regenerates post-merge.
 */
function check() {
  const { contents } = buildTable();
  const current = existsFile(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
  if (current === contents) {
    process.stdout.write(`route-lastmod: ${relative(REPO, OUTPUT)} is up to date\n`);
    return;
  }

  const parse = (text) =>
    Object.fromEntries(
      [...text.matchAll(/^\s*"([^"]+)":\s*"([^"]+)",$/gm)].map((m) => [m[1], m[2]]),
    );
  const before = parse(current);
  const after = parse(contents);

  const lines = [];
  for (const pattern of new Set([...Object.keys(before), ...Object.keys(after)]).values()) {
    if (before[pattern] === after[pattern]) continue;
    lines.push(`  ${pattern}: ${before[pattern] ?? "(absent)"} → ${after[pattern] ?? "(absent)"}`);
  }

  process.stderr.write(
    `route-lastmod: ${relative(REPO, OUTPUT)} is stale.\n${lines.sort().join("\n")}\n` +
      "Regenerate with: node scripts/generate-route-lastmod.mjs\n",
  );
  process.exitCode = 1;
}

if (process.argv.includes("--check")) {
  check();
} else {
  main();
}
