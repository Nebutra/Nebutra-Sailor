#!/usr/bin/env node

// CI guard: i18n message catalogs must NOT contain raw brand identity literals.
//
// Phase 4 of brand-meta-replacement-governance (Option A — standalone,
// mirrors lint-phosphor-marketing-only.mjs).
//
// Brand identity strings must use ICU placeholders ({brandName}, etc.)
// injected at request time by injectBrandVars() in
// apps/landing-page/src/i18n/request.ts from the single @nebutra/brand
// metadata object.
//
// Banned literals in message catalog JSON string values:
//   • "Nebutra"               → use {brandName}
//   • "云毓智能"                → use {brandNameCn}
//   • "无锡云毓"                → use {companyLegal}
//   • "Wuxi Nebutra"          → use {companyLegalEn}
//
// Governed scope: apps/landing-page/messages/*.json only.
//   Other apps have different i18n setups and are separately governed.
//
// Run: node scripts/lint-i18n-brand-literals.mjs
// Exit 1 on any raw brand literal found in a message catalog value.

import { readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const MESSAGES_DIR = join(REPO_ROOT, "apps/landing-page/messages");

/** Banned brand identity literals (case-sensitive). */
const BANNED_LITERALS = ["Nebutra", "云毓智能", "无锡云毓", "Wuxi Nebutra"];

/** Recursively walk JSON values and collect violations. */
function collectViolations(obj, path, filename, results) {
  if (typeof obj === "string") {
    for (const literal of BANNED_LITERALS) {
      if (obj.includes(literal)) {
        results.push({ file: filename, path, value: obj, matched: literal });
        return; // one violation per path
      }
    }
    return;
  }
  if (obj === null || typeof obj !== "object") return;
  if (Array.isArray(obj)) {
    for (let i = 0; i < obj.length; i++) {
      collectViolations(obj[i], `${path}[${i}]`, filename, results);
    }
    return;
  }
  for (const [k, v] of Object.entries(obj)) {
    collectViolations(v, path ? `${path}.${k}` : k, filename, results);
  }
}

let files;
try {
  files = readdirSync(MESSAGES_DIR)
    .filter((f) => f.endsWith(".json"))
    .sort();
} catch {
  process.stderr.write(`lint-i18n-brand-literals: cannot read messages dir: ${MESSAGES_DIR}\n`);
  process.exit(1);
}

const allViolations = [];
for (const filename of files) {
  const filePath = join(MESSAGES_DIR, filename);
  let data;
  try {
    data = JSON.parse(readFileSync(filePath, "utf-8"));
  } catch (err) {
    process.stderr.write(`lint-i18n-brand-literals: failed to parse ${filename}: ${err.message}\n`);
    process.exit(1);
  }
  collectViolations(data, "", filename, allViolations);
}

if (allViolations.length === 0) {
  process.stdout.write(
    "✅ lint-i18n-brand-literals: clean. No raw brand literals in message catalogs.\n",
  );
  process.exit(0);
}

process.stderr.write(
  `\n❌ lint-i18n-brand-literals: ${allViolations.length} raw brand literal(s) found.\n\n`,
);
for (const v of allViolations.slice(0, 30)) {
  process.stderr.write(
    `  ${v.file}  ${v.path}\n` +
      `    matched: ${JSON.stringify(v.matched)}\n` +
      `    value:   ${v.value.slice(0, 120)}\n`,
  );
}
if (allViolations.length > 30) {
  process.stderr.write(`  ... and ${allViolations.length - 30} more\n`);
}
process.stderr.write(
  "\nFix: replace brand literals with ICU placeholders injected by injectBrandVars():\n" +
    "  {brandName}      → brand.name\n" +
    "  {brandNameCn}    → brand.nameCn\n" +
    "  {companyLegal}   → brand.nameFull (Chinese legal entity)\n" +
    "  {companyLegalEn} → brand.nameFullEn (English legal entity)\n" +
    "  {productName}    → brand.name + ' Sailor'\n\n" +
    "Source: apps/landing-page/src/i18n/request.ts → injectBrandVars()\n" +
    "SSOT:   packages/design/brand/src/metadata.ts (generated by pnpm brand:apply)\n\n",
);
process.exit(1);
