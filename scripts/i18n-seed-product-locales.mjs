#!/usr/bin/env node
/**
 * Seed missing product message catalogs from en.json.
 * Uses the global PRODUCT language wheel (incl. zh-Hans / zh-Hant).
 *
 *   node scripts/i18n-seed-product-locales.mjs
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Keep in sync with packages/platform/i18n PRODUCT_LANGUAGES (minus en). */
const TARGETS = [
  "zh-Hans",
  "zh-Hant",
  "de",
  "es",
  "fr",
  "ja",
  "ko",
  "pt",
  "it",
  "nl",
  "sv",
  "da",
  "fi",
  "no",
  "pl",
  "cs",
  "ro",
  "hu",
  "el",
  "ru",
  "uk",
  "tr",
  "ar",
  "he",
  "fa",
  "hi",
  "bn",
  "ur",
  "th",
  "vi",
  "id",
  "ms",
  "sw",
];

const CATALOGS = [
  "packages/platform/i18n/locales",
  "apps/landing/messages",
  "apps/tsekaluk-dev/messages",
  "apps/forge/messages",
  "apps/router/messages",
];

let seeded = 0;
for (const rel of CATALOGS) {
  const dir = join(REPO, rel);
  if (!existsSync(dir)) {
    console.warn(`skip missing dir ${rel}`);
    continue;
  }
  const en = join(dir, "en.json");
  if (!existsSync(en)) {
    console.warn(`skip no en.json in ${rel}`);
    continue;
  }
  // Prefer Simplified Chinese as seed for Traditional if present
  const hans = join(dir, "zh-Hans.json");
  const legacyZh = join(dir, "zh.json");
  if (!existsSync(hans) && existsSync(legacyZh)) {
    copyFileSync(legacyZh, hans);
    console.log(`migrate ${rel}/zh.json → zh-Hans.json`);
    seeded++;
  }
  for (const loc of TARGETS) {
    const dest = join(dir, `${loc}.json`);
    if (existsSync(dest)) continue;
    // Always seed from English so SenseNova translates every leaf.
    // (Copying zh-Hans → zh-Hant skips Hant conversion because strings ≠ en.)
    // Only legacy bare-zh migration uses a Chinese source.
    const src = loc === "zh-Hans" && existsSync(legacyZh) && !existsSync(hans) ? legacyZh : en;
    copyFileSync(src, dest);
    console.log(`seed ${rel}/${loc}.json`);
    seeded++;
  }
}

// Regenerate product-locales.generated.ts from web catalog files
const localesDir = join(REPO, "packages/platform/i18n/locales");
const files = readdirSync(localesDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .filter((f) => f !== "zh") // legacy stem — not a product key
  .sort((a, b) => a.localeCompare(b));
const out = join(REPO, "packages/platform/i18n/src/product-locales.generated.ts");
const body = `/**
 * AUTO-GENERATED by scripts/i18n-seed-product-locales.mjs — do not hand-edit.
 * Source of truth: packages/platform/i18n/locales/*.json
 * Chinese catalogs: zh-Hans (Simplified) + zh-Hant (Traditional) — CLDR multi-script.
 */
export const PRODUCT_MESSAGE_LOCALES = ${JSON.stringify(files, null, 2)} as const;

export type ProductMessageLocale = (typeof PRODUCT_MESSAGE_LOCALES)[number];

export const DEFAULT_PRODUCT_MESSAGE_LOCALE = "en" as const;
`;
mkdirSync(dirname(out), { recursive: true });

// write via import fs
import { writeFileSync } from "node:fs";

writeFileSync(out, body);
console.log(`Wrote ${out} (${files.length} locales)`);
console.log(`Done. seeded=${seeded}`);
