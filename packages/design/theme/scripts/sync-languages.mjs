#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
/**
 * Generate design-language catalog artifacts from brands + meta.
 *
 * SSOT package data: packages/design/tokens/brands/<id>/brand.json
 * SSOT catalog copy: packages/design/theme/src/languages.meta.json
 *
 * Generated (DO NOT hand-edit):
 *   - src/languages.json
 *   - src/built-in-packages.generated.ts
 *
 * Usage: node scripts/sync-languages.mjs
 */
import { formatGenerated } from "../../tokens/scripts/format-generated.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../../..");
const tokensRoot = resolve(packageRoot, "..", "tokens");
const brandsDir = join(tokensRoot, "brands");
const metaPath = join(packageRoot, "src", "languages.meta.json");
const languagesOut = join(packageRoot, "src", "languages.json");
const builtInOut = join(packageRoot, "src", "built-in-packages.generated.ts");

if (!existsSync(metaPath)) {
  throw new Error(`Missing ${metaPath}`);
}
if (!existsSync(brandsDir)) {
  throw new Error(`Missing brands dir ${brandsDir}`);
}

const meta = JSON.parse(readFileSync(metaPath, "utf8"));
const compatibility = {
  tailwind: "4",
  cssVariables: true,
  brandPackage: true,
  dataBrand: true,
};

const factoryMeta = meta.factory ?? {};
const languages = [
  {
    id: "factory",
    name: factoryMeta.name ?? "Nebutra Factory",
    kind: "design-language",
    description: factoryMeta.description ?? "Default product chrome (no skin).",
    proves: factoryMeta.proves ?? [],
    darkDefault: factoryMeta.darkDefault ?? true,
    brandPath: null,
    skinPath: null,
    install: {
      command: "nebutra theme use factory",
      cssImport: null,
    },
    compatibility,
  },
];

const brandIds = readdirSync(brandsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const langMeta = meta.languages ?? {};
const missingMeta = [];

for (const id of brandIds) {
  const brandPath = join(brandsDir, id, "brand.json");
  if (!existsSync(brandPath)) {
    process.stderr.write(`warn: brands/${id} has no brand.json — skip\n`);
    continue;
  }
  const brand = JSON.parse(readFileSync(brandPath, "utf8"));
  const entryMeta = langMeta[id];
  if (!entryMeta) {
    missingMeta.push(id);
  }
  languages.push({
    id: brand.id || id,
    name: brand.name || id,
    kind: "design-language",
    description: entryMeta?.description ?? `${brand.name || id} design language.`,
    proves: entryMeta?.proves ?? [],
    darkDefault: Boolean(brand.darkDefault),
    brandPath: `brands/${id}/brand.json`,
    skinPath: `skins/${id}.css`,
    install: {
      command: `nebutra theme use ${id}`,
      cssImport: `@nebutra/tokens/skins/${id}.css`,
    },
    compatibility,
  });
}

if (missingMeta.length > 0) {
  process.stderr.write(
    `warn: languages.meta.json missing entries for: ${missingMeta.join(", ")}\n` +
      `  (generated with fallback description; add proves/description to meta)\n`,
  );
}

const orphanMeta = Object.keys(langMeta).filter((id) => !brandIds.includes(id));
if (orphanMeta.length > 0) {
  process.stderr.write(
    `warn: languages.meta.json has unused keys (no brands/<id>): ${orphanMeta.join(", ")}\n`,
  );
}

const registry = {
  $schema: "https://nebutra.com/schemas/design-language-registry.json",
  version: meta.version ?? "2026.07",
  defaultLanguage: meta.defaultLanguage ?? "factory",
  description:
    meta.description ?? "Design-language catalog for global product chrome swap (Brand Packages).",
  languages,
};

writeFileSync(languagesOut, `${JSON.stringify(registry, null, 2)}\n`);

// ── built-in-packages.generated.ts ───────────────────────────────────────────
const importLines = brandIds.map(
  (id) =>
    `import ${safeIdent(id)} from "@nebutra/tokens/brands/${id}/brand.json" with { type: "json" };`,
);
const mapEntries = brandIds.map(
  (id) => `  ${JSON.stringify(id)}: ${safeIdent(id)} as BrandPackage,`,
);

const builtInTs = `/**
 * AUTO-GENERATED by scripts/sync-languages.mjs — DO NOT EDIT.
 * Built-in Brand Packages for applyLanguage(id) without manual JSON import.
 * Source: packages/design/tokens/brands/<id>/brand.json
 */

import {
  type BrandPackage,
  normalizeBrandPackage,
} from "@nebutra/tokens/brand-package";
${importLines.join("\n")}

const RAW_BUILT_IN: Record<string, BrandPackage> = {
${mapEntries.join("\n")}
};

/** Normalized package for a shipped design-language id, or undefined. */
export function getBuiltInBrandPackage(id: string): BrandPackage | undefined {
  const raw = RAW_BUILT_IN[id];
  if (!raw) return undefined;
  return normalizeBrandPackage({ ...raw, id });
}

export function listBuiltInBrandIds(): string[] {
  return Object.keys(RAW_BUILT_IN);
}

export function hasBuiltInBrandPackage(id: string): boolean {
  return id in RAW_BUILT_IN;
}
`;

writeFileSync(builtInOut, builtInTs);

formatGenerated(languagesOut, builtInOut);

process.stdout.write(
  `sync-languages:\n` +
    `  languages.json: ${languages.length} languages (${brandIds.length} skins + factory)\n` +
    `  built-in-packages.generated.ts: ${brandIds.length} packages\n`,
);

/** Valid JS identifier from brand id (kebab → camel if needed; most ids are single words). */
function safeIdent(id) {
  if (/^[a-zA-Z_$][\w$]*$/.test(id)) return id;
  return id.replace(/[^a-zA-Z0-9_$]/g, "_").replace(/^(\d)/, "_$1");
}
