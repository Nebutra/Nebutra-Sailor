/**
 * The @nebutra/ui catalog — every component, where it sits, how settled it is,
 * and the demos that show it (ADR 2026-09-27 UI catalog).
 *
 * One list serves every surface: Sailor Studio renders it, the registry
 * serves its demos, and agents search it. Nothing else describes the
 * library, so nothing else can drift from it.
 *
 * Maintained by hand. `catalog.test.ts` holds it to the source tree: every
 * component file belongs to exactly one entry (or to INTERNAL_FILES), every
 * demo in ./demos belongs to exactly one entry and is named after it, and
 * tests/architecture/ui-catalog.test.ts keeps `status` true to the callers
 * the repo actually has.
 */

