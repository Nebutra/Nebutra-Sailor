export type CatalogCategory = (typeof CATALOG_CATEGORIES)[number]["id"];

/**
 * stable       — at least one app or package outside @nebutra/ui imports it.
 * experimental — nothing outside the library uses it yet; shown, not promised.
 */
export type CatalogStatus = "stable" | "experimental";

export type CatalogImport =
  | "@nebutra/ui/primitives"
  | "@nebutra/ui/components"
  | "@nebutra/ui/patterns"
  | "@nebutra/ui/layout";

export interface CatalogEntry {
  /** kebab-case, unique; also the prefix of every demo id it owns */
  id: string;
  title: string;
  category: CatalogCategory;
  status: CatalogStatus;
  /** the entry point an app imports it from */
  import: CatalogImport;
  /** source files, relative to packages/design/ui/src */
  files: readonly string[];
  /** demo ids — files in ./demos — the first is the one a listing shows */
  demos: readonly string[];
}

