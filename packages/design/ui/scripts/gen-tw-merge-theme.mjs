#!/usr/bin/env node
/**
 * Generates src/utils/tw-merge-theme.generated.ts from the @theme blocks the
 * design tokens ship (packages/design/tokens/styles.css + recipe.css).
 *
 * tailwind-merge only knows Tailwind's default scale. Every utility the tokens
 * add — text-ui, shadow-ambient-md, rounded-card, ease-brand, max-w-wide — is
 * otherwise read as an unknown class: a later `rounded-lg` does not replace
 * `rounded-card`, and `shadow-primary` (a colour) deletes `shadow-ambient-md`.
 * Deriving the list from the token CSS means a new token utility is known to
 * cn() the moment it exists. `--check` fails when the committed file is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokensDir = resolve(here, "../../tokens");
const out = resolve(here, "../src/utils/tw-merge-theme.generated.ts");

/** @theme namespace → tailwind-merge theme key. */
const THEME_KEYS = {
  text: "text",
  shadow: "shadow",
  radius: "radius",
  font: "font",
  tracking: "tracking",
  leading: "leading",
  ease: "ease",
  container: "container",
  breakpoint: "breakpoint",
};
/** Namespaces tailwind-merge has no theme key for; extended as class groups. */
const CLASS_GROUPS = { duration: "duration" };

export function collect() {
  const found = {};
  for (const file of ["styles.css", "recipe.css"]) {
    const css = readFileSync(resolve(tokensDir, file), "utf8");
    for (const block of css.matchAll(/@theme[^{]*\{([\s\S]*?)\n\}/g)) {
      for (const [, ns, key] of block[1].matchAll(/^\s*--([a-z]+)-([a-z0-9-]+)\s*:/gm)) {
        if (key.includes("--")) continue; // --text-sm--line-height and friends
        if (!(ns in THEME_KEYS) && !(ns in CLASS_GROUPS)) continue;
        (found[ns] ??= new Set()).add(key);
      }
    }
  }
  return Object.fromEntries(
    Object.entries(found)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([ns, keys]) => [ns, [...keys].sort()]),
  );
}

export function render(found) {
  const theme = Object.entries(found).filter(([ns]) => ns in THEME_KEYS);
  const groups = Object.entries(found).filter(([ns]) => ns in CLASS_GROUPS);
  const list = (keys) => `[${keys.map((k) => JSON.stringify(k)).join(", ")}]`;
  return `// GENERATED by packages/design/ui/scripts/gen-tw-merge-theme.mjs — do not edit.
// Source: the @theme blocks in packages/design/tokens/{styles,recipe}.css.

export const TW_MERGE_THEME = {
${theme.map(([ns, keys]) => `  ${JSON.stringify(THEME_KEYS[ns])}: ${list(keys)},`).join("\n")}
} as const;

export const TW_MERGE_CLASS_GROUPS = {
${groups.map(([ns, keys]) => `  ${JSON.stringify(CLASS_GROUPS[ns])}: [{ ${ns}: ${list(keys)} }],`).join("\n")}
} as const;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render(collect());
  if (process.argv.includes("--check")) {
    // Compare content, not layout: biome reformats the committed file
    // (unquoted keys, wrapped arrays), which is fine.
    const normalize = (text) => text.replace(/\/\/.*$/gm, "").replace(/[\s"',]/g, "");
    const current = readFileSync(out, "utf8");
    if (normalize(current) !== normalize(next)) {
      console.error(
        `${out} is stale — run: node packages/design/ui/scripts/gen-tw-merge-theme.mjs`,
      );
      process.exit(1);
    }
    process.stdout.write("tw-merge theme: up to date\n");
  } else {
    writeFileSync(out, next);
    process.stdout.write(`wrote ${out}\n`);
  }
}
