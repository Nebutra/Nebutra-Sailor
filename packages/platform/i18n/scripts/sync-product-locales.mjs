#!/usr/bin/env node
/**
 * Discover product message catalogs → generate product-locales.generated.ts
 *
 * SSOT for "which locales we ship translations for" is locales/*.json —
 * not a hand-maintained array in TypeScript.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const localesDir = join(root, "locales");
const out = join(root, "src", "product-locales.generated.ts");

const files = readdirSync(localesDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort((a, b) => a.localeCompare(b));

if (files.length === 0) {
  throw new Error(`No locale JSON files under ${localesDir}`);
}

// Prefer en as default when present
const defaultMessage = files.includes("en") ? "en" : files[0];

const body = `/**
 * AUTO-GENERATED by scripts/sync-product-locales.mjs — do not hand-edit.
 * Source of truth: packages/platform/i18n/locales/*.json
 */
export const PRODUCT_MESSAGE_LOCALES = ${JSON.stringify(files, null, 2)} as const;

export type ProductMessageLocale = (typeof PRODUCT_MESSAGE_LOCALES)[number];

export const DEFAULT_PRODUCT_MESSAGE_LOCALE = ${JSON.stringify(defaultMessage)} as const;
`;

writeFileSync(out, body);
process.stdout.write(`Wrote ${out} (${files.length} locales: ${files.join(", ")})\n`);
