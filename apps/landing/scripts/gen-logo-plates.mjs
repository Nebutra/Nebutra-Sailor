#!/usr/bin/env node
/**
 * Writes src/lib/constants/logo-plates.generated.ts: for every curated
 * third-party logo under public/logos, the plate it sits on — computed from
 * the image, not fixed.
 *
 * A fixed white mat made white marks vanish (英诺天使, 源码资本, 中科创星 are
 * white on transparent). Instead:
 *
 * - A logo that brings its own background (an opaque, even border) sits on
 *   that colour, so the mark and the plate read as one tile.
 * - A logo on transparency sits on whichever of two quiet plates it contrasts
 *   with more — a near-white or a near-black, each tinted towards the mark's
 *   own hue — scored over every inked pixel, not an average colour, so a
 *   two-tone mark is judged by what it actually draws.
 *
 *   node scripts/gen-logo-plates.mjs          write
 *   node scripts/gen-logo-plates.mjs --check  exit 1 when the file is stale
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LOGO_DIRS = ["logos/vc", "logos/vc-global"];
const OUT = join(root, "src/lib/constants/logo-plates.generated.ts");
const SIDE = 64;

const toLinear = (c) => {
  const v = c / 255;
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
};
const luminance = ([r, g, b]) => 0.2126 * toLinear(r) + 0.7152 * toLinear(g) + 0.0722 * toLinear(b);
const contrast = (a, b) => (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
const hex = (rgb) => `#${rgb.map((c) => Math.round(c).toString(16).padStart(2, "0")).join("")}`;

function hsl(h, s, l) {
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0) * 255, f(8) * 255, f(4) * 255];
}

function rgbToHueSat([r, g, b]) {
  const [R, G, B] = [r / 255, g / 255, b / 255];
  const max = Math.max(R, G, B);
  const min = Math.min(R, G, B);
  const d = max - min;
  if (d === 0) return { h: 0, s: 0 };
  const h = max === R ? ((G - B) / d + 6) % 6 : max === G ? (B - R) / d + 2 : (R - G) / d + 4;
  return { h: h * 60, s: d / (1 - Math.abs(max + min - 1)) };
}

export async function plateFor(file) {
  const { data } = await sharp(file)
    .ensureAlpha()
    .resize(SIDE, SIDE, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .raw()
    .toBuffer({ resolveWithObject: true });
  const px = (x, y) => {
    const i = (y * SIDE + x) * 4;
    return [data[i], data[i + 1], data[i + 2], data[i + 3]];
  };

  // Own background: an opaque border of one colour.
  const border = [];
  for (let i = 0; i < SIDE; i++) border.push(px(i, 0), px(i, SIDE - 1), px(0, i), px(SIDE - 1, i));
  const opaque = border.filter((p) => p[3] > 200);
  if (opaque.length / border.length >= 0.9) {
    const mean = [0, 1, 2].map((c) => opaque.reduce((s, p) => s + p[c], 0) / opaque.length);
    const spread = Math.max(...opaque.map((p) => Math.abs(luminance(p) - luminance(mean))));
    if (spread < 0.08) return { plate: hex(mean), own: true };
  }

  // Transparent: score two tinted plates over every inked pixel.
  let hx = 0;
  let hy = 0;
  let sw = 0;
  const ink = [];
  for (let y = 0; y < SIDE; y++)
    for (let x = 0; x < SIDE; x++) {
      const p = px(x, y);
      if (p[3] < 128) continue;
      ink.push(p);
      const { h, s } = rgbToHueSat(p);
      hx += Math.cos((h * Math.PI) / 180) * s;
      hy += Math.sin((h * Math.PI) / 180) * s;
      sw += s;
    }
  if (ink.length === 0) return { plate: null, own: false };
  // A colourful mark tints its plate towards its own hue; a black or white one
  // takes the House neutrals' hue (the grays are OKLCH hue 264, ≈ hsl 225).
  const colourful = sw / ink.length > 0.15;
  const hue = colourful ? ((Math.atan2(hy, hx) * 180) / Math.PI + 360) % 360 : 225;
  const tint = colourful ? 0.12 : 0.06;
  const plates = [hsl(hue, tint, 0.96), hsl(hue, tint, 0.13)];
  const score = (plate) => {
    const L = luminance(plate);
    return ink.reduce((s, p) => s + Math.min(contrast(luminance(p), L), 7), 0) / ink.length;
  };
  const [light, dark] = plates.map(score);
  return { plate: hex(light >= dark ? plates[0] : plates[1]), own: false };
}

export async function renderPlates() {
  const entries = [];
  for (const dir of LOGO_DIRS) {
    const abs = join(root, "public", dir);
    for (const name of readdirSync(abs)
      .filter((f) => f.endsWith(".png"))
      .sort((a, b) => a.localeCompare(b, "en", { numeric: true }))) {
      const { plate, own } = await plateFor(join(abs, name));
      if (plate) entries.push([`${dir}/${name}`, plate, own]);
    }
  }
  const lines = [
    "// GENERATED by scripts/gen-logo-plates.mjs — do not edit. Run `pnpm --filter @nebutra/landing gen:logo-plates`.",
    "",
    "/**",
    " * The plate each curated third-party logo sits on, keyed by its public path.",
    " * `own`: the plate is the logo's own background colour, so it may bleed to the edge.",
    " */",
    "export const LOGO_PLATES: Readonly<Record<string, { plate: string; own: boolean }>> = {",
    ...entries.map(([k, p, o]) => `  "${k}": { plate: "${p}", own: ${o} },`),
    "};",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await renderPlates();
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== next) {
      console.error(
        "logo-plates.generated.ts is stale. Run `pnpm --filter @nebutra/landing gen:logo-plates`.",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
  }
}
